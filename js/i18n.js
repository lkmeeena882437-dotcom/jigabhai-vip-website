    function cache(el, prop) {
        if (!el.dataset.i18nOrig) el.dataset.i18nOrig = el[prop];
    }

    function t(key, lang) {
        lang = lang || document.documentElement.getAttribute('data-lang') || 'en';
        if (lang !== 'en' && STR[lang] && STR[lang][key]) return STR[lang][key];
        return null;
    }

    function apply(lang) {
        if (lang !== 'hi' && lang !== 'gu' && lang !== 'en') lang = 'en';
        var htmlLang = lang === 'hi' ? 'hi' : lang === 'gu' ? 'gu' : 'en';
        document.documentElement.lang = htmlLang;
        document.documentElement.setAttribute('data-lang', lang);

        var nodes = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < nodes.length; i++) {
            var el = nodes[i];
            var key = el.getAttribute('data-i18n');
            cache(el, 'textContent');
            var value = lang === 'en' ? el.dataset.i18nOrig : (STR[lang][key] || el.dataset.i18nOrig);
            if (value != null) el.textContent = value;
        }

        var htmlNodes = document.querySelectorAll('[data-i18n-html]');
        for (var j = 0; j < htmlNodes.length; j++) {
            var hel = htmlNodes[j];
            var hkey = hel.getAttribute('data-i18n-html');
            cache(hel, 'innerHTML');
            var hvalue = lang === 'en' ? hel.dataset.i18nOrig : (STR[lang][hkey] || hel.dataset.i18nOrig);
            if (hvalue != null) hel.innerHTML = hvalue;
        }

        var titles = document.querySelectorAll('[data-i18n-title]');
        for (var k = 0; k < titles.length; k++) {
            var tel = titles[k];
            var tkey = tel.getAttribute('data-i18n-title');
            if (!tel.dataset.i18nOrigTitle) tel.dataset.i18nOrigTitle = tel.getAttribute('title') || '';
            var tvalue = lang === 'en' ? tel.dataset.i18nOrigTitle : (STR[lang][tkey] || tel.dataset.i18nOrigTitle);
            if (tvalue) tel.setAttribute('title', tvalue);
        }

        var titleKey = t('meta.title', lang);
        if (lang === 'en') {
            if (!document.documentElement.dataset.origTitle) {
                document.documentElement.dataset.origTitle = document.title;
            }
            document.title = document.documentElement.dataset.origTitle;
        } else if (titleKey) {
            document.title = titleKey;
        }

        var desc = document.querySelector('meta[name="description"]');
        if (desc) {
            if (!desc.dataset.orig) desc.dataset.orig = desc.getAttribute('content') || '';
            var dval = lang === 'en' ? desc.dataset.orig : (STR[lang]['meta.desc'] || desc.dataset.orig);
            desc.setAttribute('content', dval);
        }

        var buttons = document.querySelectorAll('[data-set-lang]');
        for (var b = 0; b < buttons.length; b++) {
            var on = buttons[b].getAttribute('data-set-lang') === lang;
            buttons[b].classList.toggle('active', on);
            buttons[b].setAttribute('aria-pressed', on ? 'true' : 'false');
        }

        try { localStorage.setItem('jb-lang', lang); } catch (e) {}

        if (window.history && window.history.replaceState) {
            var url = new URL(window.location.href);
            if (lang === 'en') url.searchParams.delete('lang');
            else url.searchParams.set('lang', lang);
            window.history.replaceState({}, '', url.pathname + url.search + url.hash);
        }

        document.dispatchEvent(new CustomEvent('jb:lang', { detail: lang }));
    }

    document.addEventListener('click', function (e) {
        var btn = e.target.closest('[data-set-lang]');
        if (!btn) return;
        e.preventDefault();
        apply(btn.getAttribute('data-set-lang'));
    });

    function initialLang() {
        var params = new URLSearchParams(window.location.search);
        var fromUrl = params.get('lang');
        if (fromUrl === 'hi' || fromUrl === 'gu' || fromUrl === 'en') return fromUrl;
        try {
            var stored = localStorage.getItem('jb-lang');
            if (stored === 'hi' || stored === 'gu' || stored === 'en') return stored;
        } catch (e) {}
        return 'en';
    }

    window.JB_I18N = { apply: apply, t: t, STR: STR, HTML_KEYS: HTML_KEYS };

    function boot() { apply(initialLang()); }
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', boot);
    } else {
        boot();
    }
